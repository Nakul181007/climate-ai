export const INITIAL_WHAT_IF_CONFIG: WhatIfModelConfig = {
  baselineReductionAchieved: 6.0,     // 6% from independent evidence
  additionalElectricBuses: 200,       // 200 extra e-buses lever
  additionalCorridors: 3,             // 3 dedicated corridors lever
  reductionPerBusPctPoints: 0.035,    // 0.035 pct pts per bus
  reductionPerCorridorPctPoints: 1.6, // 1.6 pct pts per corridor
  busCostInrCrore: 1.2,               // INR 1.2 crore per bus
  corridorCostInrCrore: 45.0,         // INR 45 crore per corridor
  targetReductionPct: 30.0,           // 30% city commitment target
};

export function calculateWhatIfModel(config: WhatIfModelConfig): WhatIfModelResult {
  const busGain = config.additionalElectricBuses * config.reductionPerBusPctPoints;
  const corridorGain = config.additionalCorridors * config.reductionPerCorridorPctPoints;
  const projectedReductionPct = Number(
    (config.baselineReductionAchieved + busGain + corridorGain).toFixed(1)
  );

  const busCost = config.additionalElectricBuses * config.busCostInrCrore;
  const corridorCost = config.additionalCorridors * config.corridorCostInrCrore;
  const estimatedCostInrCrore = Number((busCost + corridorCost).toFixed(1));

  const targetShortfallPctPoints = Number(
    Math.max(0, config.targetReductionPct - projectedReductionPct).toFixed(1)
  );

  const targetAchieved = projectedReductionPct >= config.targetReductionPct;

  return {
    projectedReductionPct,
    estimatedCostInrCrore,
    targetShortfallPctPoints,
    targetAchieved,
  };
}
